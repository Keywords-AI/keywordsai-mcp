// Rewrites lib/shared/build-info.ts with the commit being deployed.
//
// Run from the Vercel build command (see vercel.json) so the serverless
// functions carry a build-time fallback for the deployed commit. Reads the
// Vercel / GitHub Actions env first and falls back to `git rev-parse` for
// local builds. Never run this as part of `npm run build`: it modifies a
// tracked file and is only meant for throwaway build checkouts.
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const target = resolve(dirname(fileURLToPath(import.meta.url)), '../lib/shared/build-info.ts');

function git(...args) {
  try {
    return execFileSync('git', args, { encoding: 'utf8', timeout: 2000, stdio: ['ignore', 'pipe', 'ignore'] }).trim();
  } catch {
    return '';
  }
}

const commitSha = process.env.VERCEL_GIT_COMMIT_SHA
  || process.env.GITHUB_SHA
  || git('rev-parse', 'HEAD')
  || 'unknown';
const branch = process.env.VERCEL_GIT_COMMIT_REF
  || process.env.GITHUB_REF_NAME
  || git('rev-parse', '--abbrev-ref', 'HEAD')
  || 'unknown';
const timestamp = new Date().toISOString();

const escape = (value) => value.replace(/\\/g, '\\\\').replace(/'/g, "\\'");

writeFileSync(target, `// Build-time deployment stamp.
//
// GENERATED by scripts/stamp-build-info.mjs during the Vercel build. The
// committed version of this file holds placeholders; see that script.
export const BUILD_COMMIT_SHA = '${escape(commitSha)}';
export const BUILD_BRANCH = '${escape(branch)}';
export const BUILD_TIMESTAMP = '${escape(timestamp)}';
`);

console.log(`stamped build-info: ${commitSha} (${branch}) at ${timestamp}`);
